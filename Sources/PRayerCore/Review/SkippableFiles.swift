import Foundation

/// 리뷰 버튼을 누를 때 "이 파일 N개는 빼고 리뷰할까요?" 로 물을 파일(사용자 결정 — 파일마다 고르게 하지 않고 한 번에 답한다).
///
/// 한 파일이 1,000줄 넘게 바뀌었으면 종류와 상관없이 묻는다(사용자 결정). 줄당 14토큰 어림이라 그 파일 하나가 약 1.4만
/// 토큰으로, 보통 리뷰 한 번(중앙값 58줄 PR ≈ 1.9만)에 맞먹는다. 잠금 파일은 여기 오기 전에 이미 빠지고(`LockFiles`),
/// 제외 경로에 든 것도 빠져 있다. 삭제된 파일은 묻지 않는다 — 지운 코드도 봐야 정확하게 리뷰한다(사용자 결정).
/// 바이너리(이미지)는 줄이 없어 걸리지 않는다 — 원래 이름만 간다.
///
/// 처음엔 "코드가 아닌 파일 200줄 넘게" 도 물었는데(PR 6%), 아무 파일이나 뜬다는 사용자 피드백으로 기준을 올렸다.
/// 실측(최근 PR 204개): 1,000줄이면 창이 뜨는 PR 2개(1%) — 자동 생성 설정 파일 여러 개(각 1천 줄 남짓)를
/// 한꺼번에 바꾼 PR 이었다. 1,500·2,000줄이면 한 번도 뜨지 않았다.
public enum SkippableFiles {
    public static let minLines = 1_000

    /// 물을 파일들, diff 순서대로.
    public static func find(in diff: ParsedDiff) -> [DiffFile] {
        diff.files.filter { !$0.isBinary && !$0.isDeleted && $0.changedLines >= minLines }
    }
}
